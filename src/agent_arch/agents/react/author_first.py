"""메신저 **"누가 ~한 글"** 질문을 작성자 검색으로 고정한다 (author-first).

2026-09-16 운영: "홍길동 이사님이 최근 언급한 에이전트의 역할과 권한 문서라고 공유한 링크
찾아줘" 에 에이전트가 **작성자 검색을 부르지 않고** 일반 지식검색으로 가서, AI팀 채널에
업로드된 **첨부파일(TD4 화면설계서.hwp)** 을 답으로 내놨다. 정답은 홍길동가 올린 메신저
게시글이다. 같은 질문을 짧게("…공유한거 찾아줘") 물으면 잘 찾았다.

`system.py` 에는 이미 「"누가 ~한 글/링크/문서"는 **반드시**
`mattermost_skill_find_posts_by_author`」 라고 적혀 있다. **프롬프트는 확률적이라
문장이 길어지면 샌다** — `answer_guard` docstring 의 *"프롬프트는 확률적이라 새므로
코드 가드가 결정적으로 차단한다"* 와 같은 자리다. 그래서 thread-first 와 **같은 방식**으로
첫 호출을 고정한다.

판정은 결정적(정규식)이고, 도구가 안 붙었거나 작성자 지목이 없으면 아무것도 하지 않는다.
"""
from __future__ import annotations

import re
from typing import Iterable, Optional

from agent_arch.utils.honorifics import TITLE_ALT

AUTHOR_TOOL_NAME = "mattermost_skill_find_posts_by_author"

# 작성자를 **주어로** 지목하는 말.
#
# ⚠️ 3인칭은 `님`·`씨` 또는 직급이 **반드시** 있어야 한다. 이 관문이 없으면
# `[가-힣]{2,4}` + 주격조사가 "품질**이** 어떻게" 같은 평범한 어절까지 사람으로 잡는다
# (`answer_guard` 가 같은 실수를 겪고 성씨 관문을 넣은 것과 같은 이유).
#
# ⚠️ 주격만 받고 여격(`께/한테/에게`)은 받지 않는다 — "이영희 이사님**께** 보낸 메일" 의
# 이영희은 **받는 사람**이지 작성자가 아니다.
#
# ⚠️ **높임 주격 `께서` 를 반드시 넣는다.** 처음엔 `이/가/은/는` 만 받았는데, 직급을 부를 때
# 가장 자연스러운 형태가 `이사님**께서**` 다. 2026-09-16 실사용에서 "이사님께서 최근에
# 언급하신 에이전트 문서 관련 링크 찾아줘" 가 이 구멍으로 빠져 작성자 검색이 아예 안 불렸다
# (테스트 케이스가 전부 `~님이` 라 못 걸렀다). `께서` 는 여격 `께` 와 **다른 조사**다 —
# 뒤에 `서` 가 붙으면 주어이므로, 아래 순서대로 `께서` 를 먼저 보게 둔다.
_SUBJECT_PARTICLE = r"(?:께서|이|가|은|는)"
_AUTHOR_SUBJECT_RE = re.compile(
    r"(?:내|제|본인|저)\s*(?:가|는)(?![가-힣])"                      # 1인칭
    r"|(?<![가-힣])[가-힣]{2,4}\s*(?:" + TITLE_ALT + r")?\s*(?:님|씨)\s*" + _SUBJECT_PARTICLE + r"(?![가-힣])"
    r"|(?<![가-힣])[가-힣]{2,4}\s*(?:" + TITLE_ALT + r")\s*" + _SUBJECT_PARTICLE + r"(?![가-힣])",
)

# 글을 **쓰는/올리는** 행위. 작성자 지목과 **둘 다** 있어야 발동한다.
_POST_VERB_RE = re.compile(
    r"공유(?:한|했|하신|해|한거|한\s*거)"
    r"|올린|올렸|올리신|게시(?:한|했|하신)"
    r"|(?:^|\s)쓴|쓰신|쓰셨|썼|작성(?:한|했|하신)"
    r"|보낸|보냈|전달(?:한|했|하신)"
    r"|남긴|남겼|언급(?:한|했|하신)|말한|말씀하신",
)

# **수신자가 나**인 질문. 작성자 지목이 있어도 **우선한다.**
#
# "이사님이 **나를** 언급한 링크 찾아줘" 는 작성자 검색이 아니라 **멘션 조회**
# (`mattermost_skill_find_my_mentions`)가 정답이다. 메신저는 사람을 태그하면 본문에
# **영문 핸들**(`@jsbaek`)로 저장하는데, 작성자 검색으로 가면 모델이 한글 이름("백지선")을
# `query` 에 넣어 **본문에 이름을 손으로 타이핑한 글**만 걸린다.
#
# 실측(2026-09-17): `from:miim @jsbaek` 는 **103건·최신 오늘**인데
# `from:miim 백지선` 은 **8건·최신 8월 26일**이었다. 에이전트가 후자로 찾아 "최근 것이 없다"고
# 답했다 — 못 찾은 게 아니라 엉뚱한 말로 찾은 것이다.
#
# 작성자까지 지목됐어도 멘션 조회가 먼저다. 그쪽 결과를 작성자로 거르면 되고,
# 프롬프트에 이미 그 지시가 있다("이 도구 결과를 받아 **작성자로 걸러서** 답하라").
_MENTION_TARGET_RE = re.compile(
    r"(?:나|저|본인)\s*(?:를|을)\s*(?:\S+\s*){0,2}?(?:언급|태그|멘션|호출)"
    r"|(?:날|절)\s*(?:\S+\s*){0,2}?(?:언급|태그|멘션|호출|부른|불렀)"
    r"|나\s*(?:를|을)?\s*(?:부른|불렀|찾은)"
    r"|내\s*(?:이름|아이디|핸들)\s*(?:을|를)?\s*(?:언급|태그|멘션)",
)

# 다른 도메인이 정답인 신호. 작성자 지목이 있어도 **우선한다** —
# "이영희 이사님이 보낸 메일 찾아줘" 를 메신저 글 검색으로 묶으면 0건이 된다.
# (thread_first 의 `_BROADER_SCOPE_RE` 가 지시어보다 우선하는 것과 같은 구조.)
_OTHER_DOMAIN_RE = re.compile(
    r"메일|이메일|메일함|받은편지"
    r"|일정|캘린더|미팅\s*잡|회의\s*잡|예약"
    r"|휴가|연차|근태|출퇴근"
    r"|결재|전자결재|상신|품의|전표|경비|영수증"
    # 드라이브·폴더는 **위치로 쓰일 때만** 다른 도메인이다("드라이브에 올린", "폴더 안").
    # 맨 단어로 막았더니 "DMP 드라이브로 전환 관련해 공유한 글" 처럼 **주제어**로 나온
    # 메신저 질문까지 작성자 검색에서 빠졌다(2026-10-01 실사용).
    r"|(?:드라이브|폴더)\s*(?:에|안|속)|나의\s*파일",
)


def is_author_question(text: str) -> bool:
    """**누가 쓴 글**을 찾는 질문인지.

    작성자 지목(주어)과 글 쓰는 행위가 **둘 다** 있어야 한다. 한쪽만으로는
    "이영희 이사님 연락처" (지목만) 나 "공유해줘" (행위만) 까지 걸린다.

    **수신자가 나인 질문은 양보한다** — "이사님이 나를 언급한 글" 은 멘션 조회가 정답이다.

    Args:
        text: 사용자 입력 원문.

    Returns:
        작성자 검색으로 고정해야 하면 True.
    """
    if not text or _OTHER_DOMAIN_RE.search(text):
        return False
    if _MENTION_TARGET_RE.search(text):
        return False                      # 멘션 조회가 정답이다(위 주석 참조)
    return bool(_AUTHOR_SUBJECT_RE.search(text) and _POST_VERB_RE.search(text))


def pick_author_tool(text: str, known_tool_names: Iterable[str]) -> Optional[str]:
    """첫 iteration 에 강제할 작성자 검색 도구 이름. 조건이 안 맞으면 None.

    둘 다 참이어야 한다 — 도구가 바인딩돼 있고, 작성자를 지목한 질문일 때.
    하나라도 빠지면 평소대로 모델이 고른다(fail-open).

    Args:
        text: 사용자 입력 원문.
        known_tool_names: 이 턴에 바인딩된 도구 이름들.

    Returns:
        ``"mattermost_skill_find_posts_by_author"`` 또는 None.
    """
    if AUTHOR_TOOL_NAME not in set(known_tool_names or ()):
        return None
    return AUTHOR_TOOL_NAME if is_author_question(text) else None


# `wants_link` 는 2026-09-16 리뷰에서 제거했다. "공유한 **링크** 찾아줘" 는 *URL 이 든 글*
# 을 찾으라는 뜻이 아니라 **그 글의 주소**를 달라는 뜻이라, `must_contain_link` 를 여기서
# 자동으로 켜면 첨부로 공유한 정답을 걸러낸다. 그 인자는 사용자가 "본문에 URL 있는 글" 을
# 명시적으로 요구할 때 **모델이** 넣고, 그때 0건이면 그래프가 조건을 풀어 재검색한다.
