# 도구 인벤토리성 텍스트(도메인 탐색도구 목록·폴백 안내 도메인·도구별 규칙 문단)를
# 하드코딩 대신 요청마다 렌더한다. 도구 바인딩·검색 인덱스와 동일한 enabled 필터를
# 공유해, "도구는 껐는데 프롬프트엔 남는" 불일치를 구조적으로 차단한다.

def _enabled_domains() -> list:
    """사용자에게 안내할 도메인만 골라 반환한다.

    두 가지를 따로 본다 — ``enabled`` 는 그 도메인 관문을 **쓸 수 있는가**(도구 바인딩·발견),
    ``advertise`` 는 "무엇을 할 수 있어?" 답변에 **내놓을 것인가**다. 둘을 한 키로 묶으면
    "모델은 쓰되 사용자 메뉴에는 없는" 내부 기능(장기 메모리 등)을 표현할 수 없고, 안내를
    끄려고 관문을 내리면 그 관문으로만 발견되는 retrieved 도구가 고아가 된다.

    Returns:
        list: [(tool_name, intent, examples), ...] — _DOMAIN_TOOLS 등록 순서 유지.
    """
    from agent_arch.agents.tools.tool_search import _DOMAIN_TOOLS  # 순환 import 회피(지연 로드)

    enabled = []
    for _domain, (tool_name, intent, examples) in _DOMAIN_TOOLS.items():
        cfg = settings.get_tool_config(tool_name)
        if cfg.get("enabled", True) and cfg.get("advertise", True):
            enabled.append((tool_name, intent, examples))
    return enabled


def _domain_label(intent: str) -> str:
    """intent 첫 구절을 폴백 안내용 짧은 도메인 라벨로 추출한다.

    _DOMAIN_TOOLS intent 는 ``"<라벨> — <세부>"`` 규약이며, 괄호 보충 설명은
    사용자 노출 문구에서 제거한다 (예: "사내 메신저(Mattermost) — …" → "사내 메신저").

    Args:
        intent (str): _DOMAIN_TOOLS 의 도메인 intent 문자열.

    Returns:
        str: 짧은 도메인 라벨.
    """
    return intent.split(" — ")[0].split("(")[0].strip()


def _render_domain_discovery_bullets() -> str:
    """활성 도메인 탐색도구 불릿 목록(intent + 도구명)을 렌더한다."""
    return "\n".join(
        f"- {intent} → `{tool_name}`"
        for tool_name, intent, _examples in _enabled_domains()
    )


def _render_domain_labels() -> str:
    """폴백 안내 문구용 활성 도메인 라벨을 '·' 로 이어 렌더한다."""
    return "·".join(_domain_label(intent) for _tn, intent, _ex in _enabled_domains())


