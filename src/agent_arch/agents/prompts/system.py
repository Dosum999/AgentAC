# _DOMAIN_TOOLS intent 는 라우터 카드와 공유되므로 사용자 노출 전 정제가 필요하다:
# "(※ …)" 라우팅 힌트 괄호와, 내부 식별자(백틱·영문 snake_case)가 든 문장을 걸러낸다.
_ROUTER_HINT_RE = re.compile(r"\s*\(※[^)]*\)")
_INTERNAL_TOKEN_RE = re.compile(r"`|[A-Za-z]+_[A-Za-z0-9_]+")


def _render_domain_capability_bullets() -> str:
    """기능 안내용 활성 도메인 능력 불릿을 렌더한다 (도구명·라우팅 힌트 제거).

    ``"<라벨> — <세부>"`` 규약의 intent 를 ``- **라벨**: 세부`` 불릿으로 바꾸되,
    라우터 전용 텍스트(※ 힌트, 내부 식별자 문장)는 사용자에게 보이지 않게 거른다.

    Returns:
        str: 도메인당 한 줄인 마크다운 불릿 목록.
    """
    bullets = []
    for _tool_name, intent, _examples in _enabled_domains():
        label, _, detail = intent.partition(" — ")
        detail = _ROUTER_HINT_RE.sub("", detail)
        detail = ". ".join(
            s.strip() for s in detail.split(". ") if not _INTERNAL_TOKEN_RE.search(s)
        ).strip()
        bullets.append(
            f"- **{label.strip()}**: {detail}" if detail else f"- **{label.strip()}**"
        )
    return "\n".join(bullets)


def _render_tool_guidance() -> str:
    """enabled + core 로 바인딩되는 도구의 prompt_guidance 문단을 모아 반환한다.

    guidance 는 "이 도구를 반드시/이렇게 쓰라"는 전역 규칙이라 상시 바인딩(core)
    도구에만 의미가 있다 — 도구가 꺼지면 규칙도 함께 사라진다.
    """
    from agent_arch.agents.tools.registry import ToolRegistry  # 순환 import 회피(지연 로드)
    from agent_arch.agents.tools.exposure import Exposure, resolve_exposure

    blocks = []
    for tool in ToolRegistry.get_enabled_tools():
        guidance = (getattr(tool, "prompt_guidance", "") or "").strip()
        if guidance and resolve_exposure(tool) is Exposure.CORE:
            blocks.append(guidance)
    return "\n\n".join(blocks)


def _apply_tool_sections(prompt: str) -> str:
    """PRODUCTION 프롬프트의 도구 섹션 마커를 렌더 결과로 치환한다.

    마커가 없는 프롬프트(가이드 등)에는 no-op 이다.

    Args:
        prompt (str): 마커를 포함할 수 있는 base 프롬프트.

    Returns:
        str: 마커가 렌더 결과로 치환된 프롬프트.
    """
    guidance = _render_tool_guidance()
    if guidance:
        prompt = prompt.replace("<<TOOL_GUIDANCE>>", guidance)
    else:
        # 규칙 문단이 없으면 마커 앞 빈 줄까지 제거해 빈 섹션이 남지 않게 한다.
        prompt = prompt.replace("\n\n<<TOOL_GUIDANCE>>", "")
    prompt = prompt.replace(
        "<<DOMAIN_DISCOVERY_BULLETS>>", _render_domain_discovery_bullets()
    )
    prompt = prompt.replace(
        "<<DOMAIN_CAPABILITY_BULLETS>>", _render_domain_capability_bullets()
    )
    prompt = prompt.replace("<<DOMAIN_LABELS>>", _render_domain_labels())
    prompt = prompt.replace("<<DOWNLOAD_CENTER_URL>>", _render_download_center_url())
    prompt = prompt.replace("<<BOT_MENTION>>", _render_bot_mention())
    return prompt


def append_screen_context(content: str, screen_path: Optional[str]) -> str:
    """마지막 user 메시지 끝에 "지금 보고 있는 화면" 을 덧붙인다. 경로가 없으면 원문 그대로.

    왜 턴마다 붙이나: 사용자는 상세 화면을 바꿔 가며 "이거 어디까지 왔어" 를 되묻는다.
    그때 모델은 앞 턴의 도구 결과가 대화 이력에 남아 있어 **도구를 다시 부르지 않고 옛 개체로
    답한다**(2026-09-09 로컬 실측: 화면을 다른 발주로 옮겼는데 두 턴 연속 같은 발주로 답했고
    그 두 턴의 tool_calls 가 0이었다). 바뀌는 값을 매 턴 눈앞에 두면 "화면이 달라졌다" 가
    모델에게 보이고, 달라졌으면 다시 조회하라는 규칙이 걸린다.

    **질문 뒤에** 붙이는 이유: 시스템 프롬프트나 이력 앞쪽에 넣으면 턴마다 프리픽스가 달라져
    캐시가 깨진다. 끝에 두면 system + 지난 턴이 바이트 동일하게 유지된다.

    Args:
        content: 사용자 질문(이미 다른 턴 블록이 붙어 있어도 된다).
        screen_path: 게이트웨이가 검증해 넘긴 현재 화면 경로(ASCII·512자). None/빈 값이면 미주입.

    Returns:
        화면 블록이 덧붙은 문자열, 또는 원문.
    """
    path = (screen_path or "").strip()
    if not path:
        return content
    block = (
        f"[현재 화면] {path}\n"
        "- 사용자가 '이거/이 발주/여기' 라고 하면 **이 화면에 열린 개체**를 뜻합니다.\n"
        "- 화면은 턴마다 바뀝니다. 앞 턴에서 조회한 결과를 재사용하지 말고 도구를 다시 호출하세요."
    )
    return f"{content}\n\n{block}"


