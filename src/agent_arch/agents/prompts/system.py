def _build_user_context(user_info: dict) -> str:
    """요청자 정보를 시스템 프롬프트 문자열로 변환한다.

    Args:
        user_info (dict): 사용자 정보 딕셔너리

    Returns:
        str: 시스템 프롬프트에 삽입할 사용자 컨텍스트 문자열
    """
    parts = ["[요청자 정보]"]
    if user_info.get("name"):
        parts.append(f"- 이름: {user_info['name']}")
    if user_info.get("username"):
        parts.append(f"- 사용자명: {user_info['username']}")
    if user_info.get("email"):
        parts.append(f"- 이메일: {user_info['email']}")
    if user_info.get("company"):
        parts.append(f"- 소속 회사: {user_info['company']}")
    if user_info.get("companies"):
        companies = user_info["companies"]
        if isinstance(companies, list):
            companies = ", ".join(map(str, companies))
        parts.append(f"- 소속 가능 회사들: {companies}")
    if role_type := user_info.get("role_type"):
        parts.append(f"- 직책 유형: {ROLE_TYPE_LABEL.get(role_type, role_type)}")
    employee = user_info.get("employee") or {}
    if isinstance(employee, dict):
        # Frappe employee는 코드(department, designation, position)와 이름
        # (*Name) 필드를 모두 제공한다. 코드는 시스템 내부 식별자이므로 LLM
        # 컨텍스트엔 사람이 읽는 이름만 넣는다 — 코드가 들어가면 LLM이 답변에
        # 그대로 인용하는 환각이 발생한 사례 있음.
        if dept := employee.get("departmentName"):
            parts.append(f"- 부서: {dept}")
        if parent_dept := employee.get("parentDepartment"):
            parts.append(f"- 상위 부서: {parent_dept}")
        if designation := employee.get("designationName"):
            parts.append(f"- 직급: {designation}")
        if position := employee.get("positionName"):
            parts.append(f"- 직책: {position}")
        if number := employee.get("employee_number"):
            parts.append(f"- 사번: {number}")

    # 권한 raw(assigned_roles/permissions/service_access)는 의도적으로 노출하지 않는다.
    # 권한은 Frappe `permissions` 기반 별도 트랙에서 다루며, LLM이 raw role 단어를
    # 격상 해석하는 환각 사례가 확인됨. 청크 가시성 판정은 코드 단(guide_kb)에서
    # 끝내고, LLM 은 청크의 ``permission_blocked`` 플래그만 신뢰한다.

    return "\n".join(parts)


_KO_WEEKDAYS = ("월", "화", "수", "목", "금", "토", "일")


def _fmt_day(d) -> str:
    """date/datetime → 'YYYY-MM-DD (요일)' 한국어 표기."""
    return f"{d.strftime('%Y-%m-%d')} ({_KO_WEEKDAYS[d.weekday()]})"


def _build_datetime_context() -> str:
    """KST 기준 현재 날짜/시간 + 상대 날짜 기준표를 반환한다.

    '다음주 월요일'·'내일' 같은 상대 표현의 날짜 산술을 LLM 에 맡기면
    (특히 thinking off 인 프로바이더에서) off-by-one 오류가 난다.
    이번주·다음주 각 요일의 절대 날짜를 코드에서 미리 계산해 제공하여,
    모델이 '계산'이 아니라 '조회'만 하도록 만든다.

    **사용자가 말하는 문구를 그대로 키로 쓴다**("- 다음주 수요일: 2026-08-19 (수)").
    예전에는 압축 목록("- 다음 주: 월 08-17 · 화 08-18 · 수 08-19 · …")이었는데, 날짜가
    분명히 있어도 사용자 발화("다음주 수요일")와 **글자가 일치하는 항목이 없어** 모델이
    (1) '다음 주' 줄 찾기 (2) '수' 짚기 (3) 옆 날짜 읽기 3단계를 해야 했고, thinking 이
    꺼진 프로바이더는 그 대신 암산으로 새어 요일 인덱스를 1-base 로 잡는 off-by-one 을
    냈다(실측 2026-08-10: '다음주 수요일'→08-20(목). 다음주 월요일 08-17 + 3).
    문구를 통째로 키로 박으면 파싱도 산수도 없는 순수 문자열 조회가 된다.

    Returns:
        str: 현재 날짜/시각 및 상대 날짜 기준표가 포함된 컨텍스트 문자열
    """
    now = datetime.now(_KST)
    today = now.date()
    this_mon = today - timedelta(days=today.weekday())  # 이번 주 월요일
    next_mon = this_mon + timedelta(days=7)             # 다음 주 월요일

    week_lines = "\n".join(
        f"- {label} {_KO_WEEKDAYS[i]}요일: {_fmt_day(mon + timedelta(days=i))}"
        for label, mon in (("이번주", this_mon), ("다음주", next_mon))
        for i in range(7)
    )

    return (
        "[현재 날짜/시간]\n"
        f"- 오늘: {_fmt_day(today)}\n"
        f"- 현재 시각: {now.strftime('%H:%M KST')}\n"
        f"- 내일: {_fmt_day(today + timedelta(days=1))}\n"
        f"- 모레: {_fmt_day(today + timedelta(days=2))}\n"
        f"{week_lines}\n"
        "- 상대 날짜('다음주 수요일','내일' 등)는 위 목록에서 **같은 문구를 찾아 그 날짜를 "
        "그대로** 쓰세요. 요일 번호를 세거나 날짜를 더하고 빼서 계산하지 마세요.\n"
        "- 이 규칙은 조회든 등록·수정 같은 실행이든 동일합니다."
    )


